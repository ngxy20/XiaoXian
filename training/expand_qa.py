def main():
    if not os.path.exists(PATH):
        raise SystemExit(f"未找到题库：{PATH}")
    wb = load_workbook(PATH)
    ws = wb.worksheets[0]
    existing = set()
    for row in ws.iter_rows(min_row=2, values_only=True):
        if row and len(row) > 1 and row[1]:
            existing.add(str(row[1]).strip())
    added = 0
    for cat, q, a in NEW:
        if q.strip() in existing:
            continue
        ws.append([cat, q, a])
        existing.add(q.strip())
        added += 1
    wb.save(PATH)
    print(f"新增 {added} 条，当前共 {ws.max_row - 1} 条")


if __name__ == "__main__":
    main()
